#!/usr/bin/env python3
"""Run the hostile-input suite through the `coreav` binary.

The suite is generated by tools/hostile/generate.py, whose
manifest marks each file `reject` (a structured error at probe time) or
`bounded` (any result). Every file goes through native probe and
`coreav ffprobe -of json -show_error -show_format -show_streams`:
  - `reject`: native exit code 1, empty stdout, one `coreav.error/1` object on stderr;
    or, for a disallowed codec in an MP4/MOV container, exit code 0 with that
    stream dropped and reported (W1-4), in
    which case `--strict` must then reject the file with exit code 1;
    ffprobe exit code 1 requires its JSON error object on stdout.
    ffprobe lists disallowed codecs without decoding them; an accepted
    reject case is allowed only when native strict probe rejects its codec;
  - `bounded`: exit code 0 with one JSON object on stdout, or exit code 1 as
    above;
  - never a crash (signal), a timeout or an exit code other than 0 or 1.
Matroska and WebM files also go through the commands that walk their
blocks: `probe --scan-frame-sizes`, `check` under the
web-upload policy and `remux`; transport streams through
`probe --scan-frame-sizes`, which lists every access unit.
Each must end with exit code 0, or 1 with
either a `coreav.error/1` object on stderr or (for `check`) a
`coreav.verdict/1` on stdout, within the same limits.
Each run is limited to TIMEOUT seconds and, through RLIMIT_AS, to MEMORY
bytes of address space.

With --thumbnail (a build with the ffmpeg-fallback feature), every file also
goes through `coreav thumbnail` in keyframe and exact mode; with --mutate DIR,
so do flipped-byte copies of the video fixtures in DIR (decode-level hostile
input). Each run must end with exit 0 and an image, or exit 1 and an error
object, within the same limits (docs/design/decode.md, bar 2).

With --transcode ARGS (ARGS name the encoder program, as `--encoder x264
--x264 PATH`), every file (and, with --mutate DIR, the same flipped-byte
copies) also goes through `coreav transcode` at `--preset ultrafast`:
exit 0 with a `coreav.transcode/1` summary and the output file, or exit 1
with an error object, within the same limits, and nothing left beside the
output (no spool file, and no output after an error)
(docs/design/transcode.md, bar B6).

Usage: cli_hostile_check.py --coreav PATH --suite DIR [--thumbnail] [--transcode ARGS] [--mutate DIR]
Exit 0 when every case passes, 1 otherwise, 2 for a harness error.
Uses only the Python standard library.
"""
import argparse
import json
import os
import pathlib
import resource
import shlex
import subprocess
import sys
import tempfile

TIMEOUT = 10
ROOT = pathlib.Path(__file__).resolve().parent.parent
MATROSKA = ('.mkv', '.webm', '.mka')
MPEGTS = ('.ts', '.m2ts', '.mts', '.m2t')
POLICY = ROOT / 'docs' / 'schema' / 'policy-examples' / 'web-upload.json'
MEMORY = 1 << 30
CHILD_ENV = dict(os.environ, COREAV_STRICT_SAFE='1')
KINDS = {'invalid_structure', 'truncated_structure', 'limit', 'unsupported_container',
         'unsupported_feature', 'codec_not_allowed', 'io'}
# `coreav thumbnail` also fails with these (docs/schema/thumbnail-v1.md).
THUMBNAIL_KINDS = KINDS | {'decode', 'out_of_range'}
# `coreav transcode` (docs/schema/transcode-v1.md, "Errors").
TRANSCODE_KINDS = KINDS | {'decode'}
# Each transcode's limit: the encoder is a process of its own, given its own
# share of the time.
TRANSCODE_TIMEOUT = 30


def limit_memory():
    resource.setrlimit(resource.RLIMIT_AS, (MEMORY, MEMORY))


def dropped(document):
    """The output reports at least one stream left out by the allowlist."""
    return bool(document.get('dropped_streams'))


def check(coreav, path, outcome, compat, strict=False):
    argv = ([coreav, 'ffprobe', '-of', 'json', '-show_error', '-show_format', '-show_streams', str(path)]
            if compat else [coreav, 'probe', str(path)])
    argv += ['--strict'] if strict else []
    try:
        done = subprocess.run(argv, capture_output=True, timeout=TIMEOUT, check=False,
                              preexec_fn=limit_memory, env=CHILD_ENV)
    except subprocess.TimeoutExpired:
        return 'timeout'
    if done.returncode < 0:
        return f'killed by signal {-done.returncode}'
    if done.returncode == 1:
        if compat:
            try:
                error = json.loads(done.stdout).get('error', {})
            except json.JSONDecodeError:
                return 'exit 1 without a JSON error on stdout'
            if not isinstance(error.get('code'), int) or not error.get('string'):
                return f'invalid ffprobe error object: {error}'
            return None
        if done.stdout:
            return 'exit 1 with output on stdout'
        try:
            error = json.loads(done.stderr)
        except json.JSONDecodeError:
            return 'exit 1 without a JSON error on stderr'
        if error.get('schema') != 'coreav.error/1' or error.get('kind') not in KINDS:
            return f'invalid error object: {error}'
        return None
    if done.returncode == 0:
        try:
            document = json.loads(done.stdout)
        except json.JSONDecodeError:
            return 'exit 0 without JSON on stdout'
        if outcome == 'reject':
            if compat:
                try:
                    native = subprocess.run([coreav, 'probe', '--strict', str(path)],
                                            capture_output=True, timeout=TIMEOUT, check=False,
                                            preexec_fn=limit_memory, env=CHILD_ENV)
                except subprocess.TimeoutExpired:
                    return 'timeout'
                try:
                    codec_rejected = (native.returncode == 1 and not native.stdout
                                      and json.loads(native.stderr).get('kind') == 'codec_not_allowed')
                except json.JSONDecodeError:
                    codec_rejected = False
                return None if codec_rejected else 'accepted a file that must be rejected'
            if strict or not dropped(document):
                return 'accepted a file that must be rejected'
            # Dropped at probe time; strict mode must reject the file.
            return check(coreav, path, outcome, compat, strict=True)
        return None
    return f'unexpected exit code {done.returncode}'


def walking_ops(coreav, path, labelled):
    """The commands that walk every frame of a file: a list of problems,
    empty when every one ends cleanly."""
    problems = []
    with tempfile.TemporaryDirectory() as tmp:
        for label, argv in labelled(tmp):
            try:
                done = subprocess.run(argv, capture_output=True, timeout=TIMEOUT, check=False,
                                      preexec_fn=limit_memory)
            except subprocess.TimeoutExpired:
                problems.append(f'{label}: timeout')
                continue
            if done.returncode < 0:
                problems.append(f'{label}: killed by signal {-done.returncode}')
            elif done.returncode not in (0, 1):
                problems.append(f'{label}: unexpected exit code {done.returncode}')
            elif done.returncode == 1:
                try:
                    if done.stdout:
                        ok = json.loads(done.stdout).get('schema') == 'coreav.verdict/1' and label == 'check'
                    else:
                        error = json.loads(done.stderr)
                        ok = error.get('schema') == 'coreav.error/1' and error.get('kind') in KINDS
                except json.JSONDecodeError:
                    ok = False
                if not ok:
                    problems.append(f'{label}: exit 1 without a verdict or an error object')
    return problems


def matroska_ops(coreav, path):
    """`probe --scan-frame-sizes`, `check` and `remux`, which walk a
    Matroska or WebM file's blocks."""
    return walking_ops(coreav, path, lambda tmp: (
        ('scan', [coreav, 'probe', '--scan-frame-sizes', str(path)]),
        ('check', [coreav, 'check', '--policy', str(POLICY), str(path)]),
        ('remux', [coreav, 'remux', str(path), str(pathlib.Path(tmp) / 'out.mp4')])))


def mpegts_ops(coreav, path):
    """`probe --scan-frame-sizes`, which lists every access unit of a
    transport stream."""
    return walking_ops(coreav, path, lambda tmp: (
        ('scan', [coreav, 'probe', '--scan-frame-sizes', str(path)]),))


IMAGES = []  # thumbnail runs that ended with an image, for the coverage check
TRANSCODED = []  # transcode runs that ended with an output, for the coverage check


def thumbnail_ops(coreav, path, expect=None):
    """`coreav thumbnail` on a file, keyframe and exact mode, through the
    decode boundary and the sandboxed worker (docs/design/decode.md, bar
    2): a list of problems, empty when every run ends with an image and a
    summary, or exit 1 with an error object, within the limits. With
    `expect`, every run must end with an error of that kind."""
    problems = []
    with tempfile.TemporaryDirectory() as tmp:
        out = pathlib.Path(tmp) / 'out.jpg'
        for label, extra in (('thumbnail', []), ('thumbnail --exact', ['--exact', '--at', '1'])):
            argv = [coreav, 'thumbnail', str(path), '--width', '64', '--timeout', str(TIMEOUT - 2),
                    '-o', str(out), '--force', *extra]
            try:
                done = subprocess.run(argv, capture_output=True, timeout=TIMEOUT, check=False,
                                      preexec_fn=limit_memory)
            except subprocess.TimeoutExpired:
                problems.append(f'{label}: timeout')
                continue
            if done.returncode < 0:
                problems.append(f'{label}: killed by signal {-done.returncode}')
            elif done.returncode == 0:
                try:
                    ok = json.loads(done.stdout).get('schema') == 'coreav.thumbnail/1' and out.is_file()
                except json.JSONDecodeError:
                    ok = False
                if ok:
                    IMAGES.append(path.name)
                if not ok:
                    problems.append(f'{label}: exit 0 without a summary and an image')
                elif expect:
                    problems.append(f'{label}: an image where a {expect} error was due')
            elif done.returncode == 1:
                try:
                    error = json.loads(done.stderr)
                    ok = error.get('schema') == 'coreav.error/1' and error.get('kind') in THUMBNAIL_KINDS
                except json.JSONDecodeError:
                    ok = False
                if not ok or done.stdout:
                    problems.append(f'{label}: exit 1 without an error object')
                elif expect and error.get('kind') != expect:
                    problems.append(f"{label}: a {error.get('kind')} error where a {expect} error was due")
            else:
                problems.append(f'{label}: unexpected exit code {done.returncode}')
    return problems


def transcode_ops(coreav, path, encoder):
    """`coreav transcode` on a file with the encoder program `encoder`
    (docs/design/transcode.md, bar B6): a list of problems, empty when the
    run ends with exit 0, a summary and the output file, or with exit 1 and
    an error object, within the limits, leaving nothing but that output."""
    label = 'transcode'
    with tempfile.TemporaryDirectory() as tmp:
        out = pathlib.Path(tmp) / 'out.mp4'
        argv = [coreav, 'transcode', str(path), str(out), '--preset', 'ultrafast',
                '--timeout', str(TRANSCODE_TIMEOUT - 5), *encoder]
        try:
            done = subprocess.run(argv, capture_output=True, timeout=TRANSCODE_TIMEOUT, check=False,
                                  preexec_fn=limit_memory)
        except subprocess.TimeoutExpired:
            return [f'{label}: timeout']
        problems = []
        if done.returncode < 0:
            problems.append(f'{label}: killed by signal {-done.returncode}')
        elif done.returncode == 0:
            try:
                ok = json.loads(done.stdout).get('schema') == 'coreav.transcode/1' and out.is_file()
            except json.JSONDecodeError:
                ok = False
            if ok:
                TRANSCODED.append(path.name)
            else:
                problems.append(f'{label}: exit 0 without a summary and an output')
        elif done.returncode == 1:
            try:
                error = json.loads(done.stderr)
                ok = error.get('schema') == 'coreav.error/1' and error.get('kind') in TRANSCODE_KINDS
            except json.JSONDecodeError:
                ok = False
            if not ok or done.stdout:
                problems.append(f'{label}: exit 1 without an error object')
        else:
            problems.append(f'{label}: unexpected exit code {done.returncode}')
        left = sorted(p.name for p in pathlib.Path(tmp).iterdir()
                      if not (done.returncode == 0 and p == out))
        if left:
            problems.append(f'{label}: left {", ".join(left)}')
    return problems


def mutated(source, out_dir, count, seed):
    """`count` copies of `source` with bytes flipped in its second half,
    where the media data of the fixtures is: decode-level hostile input."""
    import random
    data = source.read_bytes()
    rng = random.Random(f'{seed}:{source.name}')
    paths = []
    for i in range(count):
        copy = bytearray(data)
        half = len(copy) // 2
        for _ in range(max(1, len(copy) // 2000)):
            at = rng.randrange(half, len(copy))
            copy[at] ^= 1 << rng.randrange(8)
        path = out_dir / f'{source.stem}-mut{i}{source.suffix}'
        path.write_bytes(bytes(copy))
        paths.append(path)
    return paths


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--coreav', required=True)
    parser.add_argument('--suite', required=True, type=pathlib.Path)
    parser.add_argument('--thumbnail', action='store_true',
                        help='also run coreav thumbnail on every file (a build with the ffmpeg-fallback feature)')
    parser.add_argument('--transcode', metavar='ARGS',
                        help='also run coreav transcode on every file, with these encoder options '
                             '(for example "--encoder x264 --x264 PATH")')
    parser.add_argument('--mutate', type=pathlib.Path,
                        help='with --thumbnail or --transcode: also run them on flipped-byte copies of the video '
                             'files in this directory')
    args = parser.parse_args()
    encoder = shlex.split(args.transcode) if args.transcode else None
    manifest = json.loads((args.suite / 'manifest.json').read_text())
    cases = manifest.get('cases')
    if not cases:
        print('harness error: manifest has no cases', file=sys.stderr)
        return 2
    failures = []
    counts = {'reject': 0, 'bounded': 0}
    for case in cases:
        outcome = case['outcome']
        if outcome not in counts:
            print(f"harness error: unknown outcome {outcome}", file=sys.stderr)
            return 2
        counts[outcome] += 1
        for compat in (False, True):
            problem = check(args.coreav, args.suite / case['name'], outcome, compat)
            if problem:
                failures.append({'file': case['name'], 'outcome': outcome,
                                 'compat': compat, 'problem': problem})
        suffix = (args.suite / case['name']).suffix.lower()
        ops = matroska_ops if suffix in MATROSKA else mpegts_ops if suffix in MPEGTS else None
        if ops:
            for problem in ops(args.coreav, args.suite / case['name']):
                failures.append({'file': case['name'], 'outcome': outcome, 'problem': problem})
        if args.thumbnail:
            for problem in thumbnail_ops(args.coreav, args.suite / case['name'], case.get('thumbnail_kind')):
                failures.append({'file': case['name'], 'outcome': outcome, 'problem': problem})
        if encoder is not None:
            for problem in transcode_ops(args.coreav, args.suite / case['name'], encoder):
                failures.append({'file': case['name'], 'outcome': outcome, 'problem': problem})
    if encoder is not None:
        counts['transcoded'] = len(TRANSCODED)
    if (args.thumbnail or encoder is not None) and args.mutate:
        counts['mutated'] = 0
        before, transcoded_before = len(IMAGES), len(TRANSCODED)
        with tempfile.TemporaryDirectory() as tmp:
            for source in sorted(args.mutate.iterdir()):
                if source.suffix.lower() not in ('.mp4', '.mov', '.mkv', '.webm'):
                    continue
                for path in mutated(source, pathlib.Path(tmp), 3, 207):
                    counts['mutated'] += 1
                    problems = thumbnail_ops(args.coreav, path) if args.thumbnail else []
                    if encoder is not None:
                        problems += transcode_ops(args.coreav, path, encoder)
                    for problem in problems:
                        failures.append({'file': path.name, 'outcome': 'bounded', 'problem': problem})
        # Mutated media data reaches the decoder only if some copies decode:
        # a suite where every run is refused before decoding tests nothing.
        if args.thumbnail:
            decoded = set(IMAGES[before:])
            counts['mutated_decoded'] = len(decoded)
            if not decoded:
                failures.append({'file': '(mutated copies)', 'outcome': 'bounded',
                                 'problem': 'no mutated copy produced an image: the decoder was never reached'})
        if encoder is not None:
            encoded = set(TRANSCODED[transcoded_before:])
            counts['mutated_transcoded'] = len(encoded)
            if not encoded:
                failures.append({'file': '(mutated copies)', 'outcome': 'bounded',
                                 'problem': 'no mutated copy was transcoded: the encoder was never reached'})
    print(json.dumps({'cases': counts, 'failures': failures}, indent=2))
    return 1 if failures else 0


if __name__ == '__main__':
    sys.exit(main())
