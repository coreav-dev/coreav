RANGES = {"u8": (0, 255), "i8": (-128, 127), "i16": (-32768, 32767), "u16": (0, 65535),
          "i32": (-(2**31), 2**31 - 1), "u32": (0, 2**32 - 1)}

C_TOKEN = re.compile(r"\s+|/\*.*?\*/|//[^\n]*|(?P<num>0[xX][0-9a-fA-F]+|\d+)[uUlL]*|(?P<id>[A-Za-z_]\w*)|(?P<op>[{},-])", re.S)


def number(text):
    """A C integer literal's value, decimal or hexadecimal."""
    return int(text, 16) if text[:2] in ("0x", "0X") else int(text)


def pinned_sources():
    """scripts/pinned_sources.py as a module."""
    spec = importlib.util.spec_from_file_location("pinned_sources", ROOT / "scripts" / "pinned_sources.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def sources(cache):
    """Path to text of every member of the RFC's code, RFC 8251 applied."""
    src = pinned_sources()
    problems = []
    files = dict(src.members("rfc6716", src.RFC6716, cache, problems))
    if problems:
        sys.exit("error: " + "; ".join(problems))
    return files


def defines(files):
    """Integer `#define`s of every header, by name, unevaluated."""
    out = {}
    for rel, text in files.items():
        if rel.endswith(".h"):
            for m in re.finditer(r"^\s*#\s*define\s+(\w+)[ \t]+([^\n]*?)\s*(?:/\*.*)?$", text, re.M):
                out.setdefault(m.group(1), m.group(2).split("//")[0].strip())
    return out


def evaluate(expr, defs, depth=0):
    """An integer `#define` expression's value: names resolved, C's
    integer division."""
    if depth > 20:
        sys.exit(f"error: cannot evaluate {expr!r}")
    expr = re.sub(r"\b([A-Za-z_]\w*)\b", lambda m: f"({evaluate(defs[m.group(1)], defs, depth + 1)})"
                  if m.group(1) in defs else sys.exit(f"error: unknown name {m.group(1)}"), expr)
    expr = re.sub(r"(\d+)[uUlL]+", r"\1", expr)
    if not re.fullmatch(r"[\d\s+\-*/()<>]*", expr):
        sys.exit(f"error: cannot evaluate {expr!r}")
    # Python's `//` rounds down where C truncates; they differ only with a
    # negative operand, which no size here has.
    if "/" in expr and "-" in expr:
        sys.exit(f"error: a division with a negative operand in {expr!r}")
    return int(eval(expr.replace("/", "//"), {"__builtins__": {}}))


def array(files, defs, rel, name):
    """The initializer of the array `name` in `rel`, as nested lists,
    checked against its declared dimensions. Its elements are numbers,
    negated numbers or names of `#define`s: no other arithmetic."""
    text = files.get(rel)
    if text is None:
        sys.exit(f"error: no file {rel}")
    m = re.search(r"\b" + re.escape(name) + r"\s*(\[[^=;]*\])\s*=\s*\{", text)
    if m is None:
        sys.exit(f"error: no array {name} in {rel}")
    # An empty dimension (`[]`) takes its size from the initializer.
    declared = [evaluate(d, defs) if d.strip() else None for d in re.findall(r"\[([^\]]*)\]", m.group(1))]
    stack = [[]]
    pos = m.end()
    # What may come next: an element after `{` or `,`, else `,` or `}`.
    element = True
    sign = 1
    # An element may be one difference of two numbers (`39083 - 65536`).
    minus = False
    while stack:
        t = C_TOKEN.match(text, pos)
        if t is None:
            sys.exit(f"error: {name}: unexpected text")
        pos = t.end()
        if t.lastgroup is None:
            continue
        tok = t.group(0)
        if tok == "-" and not element and not minus and stack[-1] and isinstance(stack[-1][-1], int):
            minus = True
            element = True
            continue
        if minus:
            if t.lastgroup != "num":
                sys.exit(f"error: {name}: a difference of anything but two numbers")
            stack[-1][-1] -= number(t.group("num"))
            minus = False
            element = False
            continue
        if (t.lastgroup in ("num", "id") or tok in "{-") != element and tok != "}":
            sys.exit(f"error: {name}: arithmetic or misplaced {tok!r} in the initializer")
        if tok == "-":
            sign = -sign
            continue
        if t.lastgroup == "num":
            stack[-1].append(sign * number(t.group("num")))
        elif t.lastgroup == "id":
            stack[-1].append(sign * evaluate(tok, defs))
        elif tok == "{":
            stack.append([])
            continue
        elif tok == "}":
            if sign < 0:
                sys.exit(f"error: {name}: a '-' with no element")
            done = stack.pop()
            if not stack:
                if [d if d is not None else s for d, s in zip(declared, shape(done))] != shape(done) or len(declared) != len(shape(done)):
                    sys.exit(f"error: {name}: dimensions {shape(done)}, declared {declared}")
                return done
            stack[-1].append(done)
        sign = 1
        element = tok == ","
    sys.exit(f"error: {name}: unterminated")


def shape(value):
    """The dimensions of a rectangular nested list."""
    if not isinstance(value, list):
        return []
    inner = {tuple(shape(v)) for v in value}
    if len(inner) != 1:
        sys.exit("error: a table that is not rectangular")
    return [len(value)] + list(inner.pop())


def rust_type(elem, dims):
    t = elem
    for d in reversed(dims):
        t = f"[{t}; {d}]"
    return t


def rust_value(value, indent):
    """A Rust array literal, ten numbers a line."""
    if not isinstance(value[0], list):
        rows = [", ".join(str(v) for v in value[i : i + 10]) for i in range(0, len(value), 10)]
        if len(rows) == 1:
            return f"[{rows[0]}]"
        pad = " " * (indent + 4)
        return "[\n" + ",\n".join(pad + r for r in rows) + ",\n" + " " * indent + "]"
    pad = " " * (indent + 4)
    return "[\n" + "".join(f"{pad}{rust_value(v, indent + 4)},\n" for v in value) + " " * indent + "]"


def flat(value):
    return [x for v in value for x in flat(v)] if isinstance(value, list) else [value]


def generate(files):
    """Our file name to its text, for every layer."""
    defs = defines(files)
    out = {}
    for layer in sorted({t[0] for t in TABLES}):
        lines = [
            "// @generated by scripts/opus_tables.py from the code of RFC 6716 Appendix A",
            "// with RFC 8251's changes; do not edit.",
            "//",
            "// Copyright (c) 2007-2012 IETF Trust, CSIRO, Xiph.Org Foundation, and the"
            if layer == "celt" else
            "// Copyright (c) 2006-2012 IETF Trust and Skype Limited, and the other",
            "// other holders NOTICE names. BSD-3-Clause; see NOTICE."
            if layer == "celt" else
            "// holders NOTICE names. BSD-3-Clause; see NOTICE.",
        ]
        for lay, ours, elem, rel, name, what in TABLES:
            if lay != layer:
                continue
            value = array(files, defs, rel, name)
            dims = shape(value)
            lo, hi = RANGES[elem]
            if not all(lo <= v <= hi for v in flat(value)):
                sys.exit(f"error: {name}: a value outside {elem}")
            lines.append("")
            lines.append(f"/// {what[0].upper()}{what[1:]}.")
            lines.append(f"pub(crate) static {ours}: {rust_type(elem, dims)} = {rust_value(value, 0)};")
        out[f"{layer}.rs"] = "\n".join(lines) + "\n"
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--cache", default=os.path.expanduser(pinned_sources().CACHE),
                    help="directory for the pinned sources")
    ap.add_argument("--check", action="store_true", help="compare with the committed files; write nothing")
    a = ap.parse_args()
    out = generate(sources(a.cache))
