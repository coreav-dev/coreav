#!/usr/bin/env python3
"""Writes the trigonometric constants of the MP3 decoder as Rust literals
(crates/coreav-audio/src/mp3/trig.rs), so that the decoder computes none at
run time: computing them would link the C math library into every build
of `coreav` and cost every process its loading (docs/design/benchmarks.md,
start-up). From ISO/IEC 11172-3 2.4.3.4 and 13818-3 2.4.3.2:

- the IMDCT windows: sin(pi/36 (i + 1/2)) (long) and sin(pi/12 (i + 1/2))
  (short);
- the short IMDCT's cosines cos(pi/24 (2i + 7)(2k + 1)), for outputs
  0..3 and 6..9 of each input line k (the symmetries of `imdct12`);
- MPEG-1 intensity stereo: tan(p pi / 12) for p = 0..5;
- MPEG-2 intensity stereo: i0^n for n = 0..15, i0 = 1/sqrt(2)
  (intensity_scale 1) and 2^(-1/4) (intensity_scale 0).

usage: gen_trig.py OUT.rs
"""
import math
import sys


def f(x):
    return f'{x!r}'


long_window = [math.sin(math.pi / 36 * (i + 0.5)) for i in range(36)]
short_window = [math.sin(math.pi / 12 * (i + 0.5)) for i in range(12)]
short_cos = [([math.cos(math.pi / 24 * (2 * i + 7) * (2 * k + 1)) for i in range(3)],
              [math.cos(math.pi / 24 * (2 * (6 + i) + 7) * (2 * k + 1)) for i in range(3)])
             for k in range(6)]
tan12 = [math.tan(p * math.pi / 12) for p in range(6)]
i0 = [[(1 / math.sqrt(2)) ** n for n in range(16)], [2 ** (-n / 4) for n in range(16)]]


def array(values):
    return '[' + ', '.join(f(v) for v in values) + ']'


text = f'''// Generated by crates/coreav-audio/tables/gen_trig.py; do not edit.
//! The trigonometric constants of the MP3 decoder, as literals: the decoder
//! computes none at run time, so no build links the C math library for it
//! (`tables/gen_trig.py`).
#![cfg_attr(rustfmt, rustfmt::skip)]
#![expect(clippy::approx_constant, reason = "generated: the formulas' values, some of which are named constants")]

/// sin(pi/36 (i + 1/2)): the long IMDCT window.
pub(crate) const LONG_WINDOW: [f64; 36] = {array(long_window)};

/// sin(pi/12 (i + 1/2)): the short IMDCT window.
pub(crate) const SHORT_WINDOW: [f64; 12] = {array(short_window)};

/// cos(pi/24 (2i + 7)(2k + 1)) for input line k: outputs 0..3, then 6..9.
pub(crate) const SHORT_COSINES: [([f64; 3], [f64; 3]); 6] = [
{chr(10).join(f"    ({array(lo)}, {array(hi)})," for lo, hi in short_cos)}
];

/// tan(p pi / 12): MPEG-1 intensity positions 0 to 5.
pub(crate) const TAN_12: [f64; 6] = {array(tan12)};

/// i0^n for n = 0..15: [0] i0 = 1/sqrt(2) (intensity_scale 1), [1] i0 =
/// 2^(-1/4) (intensity_scale 0).
pub(crate) const INTENSITY_POWERS: [[f64; 16]; 2] = [
    {array(i0[0])},
    {array(i0[1])},
];
'''
open(sys.argv[1], 'w').write(text)
