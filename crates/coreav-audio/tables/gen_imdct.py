#!/usr/bin/env python3
"""Writes the 18-point DCT-IV behind the long IMDCT of MP3 Layer III as
straight-line Rust over four lanes (crates/coreav-audio/src/mp3/imdct.rs):
Y[n] = sum_k x[k] cos(pi/72 (2n + 1)(2k + 1)).

The factorization: w[k] = 2 x[k] cos(pi (2k + 1) / 72) turns the DCT-IV
into a DCT-II, Z[n] = sum_k w[k] cos(pi n (2k + 1) / 36), because
2 cos(t) cos(2nt) = cos((2n + 1)t) + cos((2n - 1)t) gives Z[n] = Y[n] +
Y[n - 1], with Y[-1] = Y[0]. The 18-point DCT-II splits into a 9-point
DCT-II of w[k] + w[17 - k] (the even outputs) and a 9-point DCT-IV of
w[k] - w[17 - k] (the odd ones), that DCT-IV again by the recurrence; a
9-point DCT-II pairs inputs k and 8 - k, whose cosines are equal for even
outputs and opposite for odd ones. Checked against the direct sum here
and by the decoder tests.

usage: gen_imdct.py OUT.rs
"""
import math
import sys

lines = []
counter = [0]
mults = [0]
adds = [0]


def fresh():
    counter[0] += 1
    return f't{counter[0]}'


def emit(expr, m=0, a=0):
    t = fresh()
    lines.append(f'    let {t} = {expr};')
    mults[0] += m
    adds[0] += a
    return t


def lit(c):
    if abs(c - math.sqrt(2)) < 1e-15:
        return 'std::f32::consts::SQRT_2'
    return f'{c!r}_f32'


def dct2_odd(xs):
    """Z[m] = sum_k x[k] cos(pi m (2k + 1) / 2n), n odd."""
    n = len(xs)
    h = (n - 1) // 2
    s = [emit(f'{xs[k]} + {xs[n - 1 - k]}', a=1) for k in range(h)]
    d = [emit(f'{xs[k]} - {xs[n - 1 - k]}', a=1) for k in range(h)]
    mid = xs[h]
    out = []
    for m in range(n):
        terms = []
        for k in range(h):
            c = math.cos(math.pi * m * (2 * k + 1) / (2 * n))
            v = s[k] if m % 2 == 0 else d[k]
            if abs(c) < 1e-12:
                continue
            if abs(c - 1) < 1e-12:
                terms.append(('+', v))
            elif abs(c + 1) < 1e-12:
                terms.append(('-', v))
            else:
                terms.append(('+', f'{v} * {lit(c)}'))
                mults[0] += 1
        if m % 2 == 0:
            terms.append(('+' if math.cos(math.pi * m / 2) > 0 else '-', mid))
        expr = ''
        for sign, t in terms:
            if not expr:
                expr = t if sign == '+' else f'-{t}'
            else:
                expr += f' {sign} {t}'
                adds[0] += 1
        out.append(emit(expr))
    return out


def dct4(xs):
    """Y[n] = sum_k x[k] cos(pi (2n + 1)(2k + 1) / 4N), by the recurrence."""
    n = len(xs)
    w = [emit(f'{x} * {lit(2 * math.cos(math.pi * (2 * k + 1) / (4 * n)))}', m=1)
         for k, x in enumerate(xs)]
    z = dct2(w)
    y = [emit(f'{z[0]} * 0.5_f32', m=1)]
    for m in range(1, n):
        y.append(emit(f'{z[m]} - {y[m - 1]}', a=1))
    return y


def dct2(xs):
    n = len(xs)
    if n % 2 == 1:
        return dct2_odd(xs)
    half = n // 2
    s = [emit(f'{xs[k]} + {xs[n - 1 - k]}', a=1) for k in range(half)]
    d = [emit(f'{xs[k]} - {xs[n - 1 - k]}', a=1) for k in range(half)]
    even = dct2(s)
    odd = dct4(d)
    out = []
    for m in range(half):
        out += [even[m], odd[m]]
    return out


def check():
    """The unrolled algorithm against the direct sum, in double precision."""
    import random
    random.seed(1)
    x = [random.uniform(-1, 1) for _ in range(18)]
    env = {f'x{k}': v for k, v in enumerate(x)}
    for line in lines:
        name, expr = line.strip()[4:-1].split(' = ', 1)
        env[name] = eval(expr.replace('std::f32::consts::SQRT_2', repr(math.sqrt(2))).replace('_f32', ''), {}, env)
    for m, name in enumerate(outputs):
        direct = sum(x[k] * math.cos(math.pi / 72 * (2 * m + 1) * (2 * k + 1)) for k in range(18))
        if abs(env[name] - direct) > 1e-9:
            raise SystemExit(f'output {m}: {env[name]} != {direct}')


outputs = dct4([f'x{k}' for k in range(18)])
check()
body = '\n'.join(lines)
names = ', '.join(f'x{k}' for k in range(18))
result = ', '.join(outputs)
text = f'''// Generated by crates/coreav-audio/tables/gen_imdct.py; do not edit.
//! The 18-point DCT-IV Y[n] = sum_k x[k] cos(pi/72 (2n + 1)(2k + 1)) of the
//! long IMDCT, unrolled, over four lanes (`layer3.rs`, `imdct`).
#![cfg_attr(rustfmt, rustfmt::skip)]
#![expect(clippy::excessive_precision, reason = "generated: each constant is the double-precision value, rounded once")]

use super::lanes::F4;

/// The DCT-IV of `x`, lane by lane: {mults[0]} multiplications and
/// {adds[0]} additions per lane.
#[inline(always)]
pub(crate) fn dct4_18(x: &[F4; 18]) -> [F4; 18] {{
    let [{names}] = *x;
{body}
    [{result}]
}}
'''
open(sys.argv[1], 'w').write(text)
