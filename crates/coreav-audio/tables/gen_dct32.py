#!/usr/bin/env python3
"""Writes the 32-point DCT-II of the MP3 synthesis filter as straight-line
Rust (crates/coreav-audio/src/mp3/dct32.rs): X[m] = sum_k x[k]
cos(pi m (2k + 1) / 64), by the even/odd split of synth.rs, unrolled so
that every intermediate is a local, over four lanes. Checked against the
direct sum here
and by the synthesis tests.

usage: gen_dct32.py OUT.rs
"""
import math
import sys

lines = []
counter = [0]


def fresh():
    counter[0] += 1
    return f't{counter[0]}'


def dct(xs):
    """xs: names of the inputs; returns the names of the outputs."""
    n = len(xs)
    if n == 1:
        return xs
    half = n // 2
    even, odd = [], []
    for k in range(half):
        a, b = xs[k], xs[n - 1 - k]
        e, o = fresh(), fresh()
        f = 0.5 / math.cos(math.pi * (2 * k + 1) / (2 * n))
        lines.append(f'    let {e} = {a} + {b};')
        lines.append(f'    let {o} = ({a} - {b}) * {f!r}_f32;')
        even.append(e)
        odd.append(o)
    ee = dct(even)
    oo = dct(odd)
    out = []
    for m in range(half):
        out.append(ee[m])
        if m + 1 < half:
            t = fresh()
            lines.append(f'    let {t} = {oo[m]} + {oo[m + 1]};')
            out.append(t)
        else:
            out.append(oo[m])
    return out


def check():
    """The unrolled algorithm against the direct sum, in double precision."""
    import random
    random.seed(1)
    x = [random.uniform(-1, 1) for _ in range(32)]
    env = {f'x{k}': v for k, v in enumerate(x)}
    for line in lines:
        name, expr = line.strip()[4:-1].split(' = ', 1)
        env[name] = eval(expr.replace('_f32', ''), {}, env)
    for m, name in enumerate(outputs):
        direct = sum(x[k] * math.cos(math.pi * m * (2 * k + 1) / 64) for k in range(32))
        if abs(env[name] - direct) > 1e-9:
            raise SystemExit(f'output {m}: {env[name]} != {direct}')


outputs = dct([f'x{k}' for k in range(32)])
check()
body = '\n'.join(lines)
names = ', '.join(f'x{k}' for k in range(32))
result = ', '.join(outputs)
text = f'''// Generated by crates/coreav-audio/tables/gen_dct32.py; do not edit.
//! The 32-point DCT-II X[m] = sum_k x[k] cos(pi m (2k + 1) / 64) of the
//! synthesis filter's matrixing, unrolled, over four lanes (`synth.rs`).
#![cfg_attr(rustfmt, rustfmt::skip)]
#![expect(clippy::excessive_precision, reason = "generated: each constant is the double-precision value, rounded once")]

use super::lanes::F4;

/// The DCT of `x`, lane by lane: 80 multiplications and 209 additions per
/// lane.
#[inline(always)]
pub(crate) fn dct32(x: &[F4; 32]) -> [F4; 32] {{
    let [{names}] = *x;
{body}
    [{result}]
}}
'''
open(sys.argv[1], 'w').write(text)
