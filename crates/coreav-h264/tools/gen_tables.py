        assert len(set(vals)) == len(vals), (name, vals)
        # Prefix-free check.
        bs = [b for _, b in rows]
        for i, a in enumerate(bs):
            for j, b2 in enumerate(bs):
                assert i == j or not b2.startswith(a), (name, a, b2)
        out.append(f"/// {title.split(' – ')[0]}: (value, bin string length, bins MSB first); value -1 is the intra prefix.")
