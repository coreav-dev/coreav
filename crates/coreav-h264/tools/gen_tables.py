#!/usr/bin/env python3
"""Generate crates/coreav-h264/src/tables.rs from the ITU-T H.264 (08/2024) PDF.

Every constant table the decoder needs (VLC code tables, CABAC initialization
values, state transitions, scans, default scaling lists, deblocking
thresholds, macroblock type tables) is read from the specification's own
tables with pdfplumber, checked for shape and continuity, and written out.
No table is typed by hand, and nothing comes from another implementation.

    python3 -m venv venv && venv/bin/pip install pdfplumber==0.11.10
    venv/bin/python -I crates/coreav-h264/tools/gen_tables.py \
        --pdf h264.pdf --out crates/coreav-h264/src/tables.rs

CI regenerates the file and requires it to be byte-identical (bar S2 of
docs/design/h264.md), so the decoder's constants are the specification's,
not a transcription. The extractor is adapted from the one written for the
N2 spike, which reads the same tables
from the same PDF.

The PDF is the freely available T-REC-H.264-202408-S!!PDF-E from
https://www.itu.int/rec/T-REC-H.264-202408-I/en; it is not committed.
"""
import argparse
import hashlib
import json
import os
import tempfile
import re
import sys

import pdfplumber

PDF_SHA256 = "647d6bb2f7a62d221cd5e31da9a948e2dde32f9ac008a548f98348c838bd389d"

# Known errata in the 08/2024 PDF, each checked against the row's neighbours:
# Table 9-26 prints ctxIdx 541 as "641" (the rows run 528..571 in order).
CTXIDX_ERRATA = {641: 541}


def num(s):
    s = (s or "").replace("\n", "").replace("−", "-").replace(" ", "")
    return int(s)


def bits(s):
    """A VLC bit string from a table cell, or None for '-' / empty."""
    s = (s or "").replace("\n", "").replace(" ", "")
    if s in ("", "-"):
        return None
    if not re.fullmatch(r"[01]+", s):
        raise ValueError(f"not a bit string: {s!r}")
    return s


class Spec:
    def __init__(self, path):
        self.pdf = pdfplumber.open(path)
        self.cache = {}
        cache = os.path.join(tempfile.gettempdir(), f"h264-spec-text-{PDF_SHA256[:16]}.json")
        if os.path.exists(cache):
            self.texts = json.load(open(cache))
        else:
            self.texts = [(p.extract_text() or "") if i >= 30 else "" for i, p in enumerate(self.pdf.pages)]
            json.dump(self.texts, open(cache, "w"))

    def tables(self, page):
        if page not in self.cache:
            self.cache[page] = self.pdf.pages[page].extract_tables()
        return self.cache[page]

    def find_pages(self, title):
        """Pages (0-based) whose text contains the table title, skipping the
        table of contents."""
        return [i for i, t in enumerate(self.texts) if title in t]


def rust_bits_table(name, rows, doc):
    """rows: list of (bitstring, payload tuple)."""
    lines = [f"/// {doc}", f"pub const {name}: &[(u8, u32, {', '.join(['u8'] * len(rows[0][1]))})] = &["]
    for b, payload in rows:
        lines.append(f"    ({len(b)}, 0b{b}, {', '.join(str(x) for x in payload)}),")
    lines.append("];")
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--pdf", required=True)
    ap.add_argument("--out", required=True)
    args = ap.parse_args()
    digest = hashlib.sha256(open(args.pdf, "rb").read()).hexdigest()
    if digest != PDF_SHA256:
        sys.exit(f"unexpected PDF sha256 {digest}")
    spec = Spec(args.pdf)
    out = [
        "// @generated by crates/coreav-h264/tools/gen_tables.py from Rec. ITU-T",
        f"// H.264 (08/2024), PDF sha256 {PDF_SHA256}. Do not edit by hand.",
        "",
        "//! Constant tables of Rec. ITU-T H.264 (08/2024), read from the",
        "//! specification's own tables. See the generator for how each one is",
        "//! found and checked.",
        "",
        "#![allow(clippy::unreadable_literal)]",
        "#![forbid(unsafe_code)]",
        "",
    ]

    # ---- Table 9-5 coeff_token -------------------------------------------
    pages = spec.find_pages("Table 9-5 – coeff_token mapping")
    rows = []
    for p in pages:
        for t in spec.tables(p):
            if t and t[0] and "0 <= nC < 2" in (t[0][2] or ""):
                rows.extend(t[1:])
    cols = [[] for _ in range(6)]
    seen = set()
    for r in rows:
        t1, tc = num(r[0]), num(r[1])
        assert (t1, tc) not in seen
        seen.add((t1, tc))
        for c in range(6):
            b = bits(r[2 + c])
            if b is not None:
                cols[c].append((b, (t1, tc)))
    assert len(seen) == 62, len(seen)
    names = ["0 <= nC < 2", "2 <= nC < 4", "4 <= nC < 8", "8 <= nC", "nC == -1", "nC == -2"]
    out.append("/// Table 9-5: coeff_token as (length, code, TrailingOnes, TotalCoeff), one list per nC class:")
    out.append("/// " + ", ".join(f"{i}: {n}" for i, n in enumerate(names)) + ".")
    out.append("pub const COEFF_TOKEN: [&[(u8, u32, u8, u8)]; 6] = [")
    for c in cols:
        out.append("    &[" + ", ".join(f"({len(b)}, 0b{b}, {p[0]}, {p[1]})" for b, p in c) + "],")
    out.append("];")
    out.append("")

    # ---- Tables 9-7, 9-8 total_zeros 4x4 -----------------------------------
    tz = {}
    tz_pages = sorted(set(spec.find_pages("Table 9-7 – total_zeros tables for 4x4 blocks") + spec.find_pages("Table 9-8 – total_zeros tables for 4x4 blocks")))
    if True:
        for p in tz_pages:
            for t in spec.tables(p):
                # The 2x4 chroma DC table (Table 9-9 (b)) has the same header
                # but only 10 rows; Tables 9-7 and 9-8 have 18 and 11.
                if t and t[0] and t[0][0] == "total_zeros" and t[1][1] in ("1", "8") and len(t) >= 11:
                    idxs = [num(x) for x in t[1][1:]]
                    for r in t[2:]:
                        z = num(r[0])
                        for k, cell in zip(idxs, r[1:]):
                            b = bits(cell)
                            if b is not None:
                                tz.setdefault(k, []).append((b, (z,)))
    assert sorted(tz) == list(range(1, 16)), sorted(tz)
    for k in tz:
        assert len(tz[k]) == 17 - k, (k, len(tz[k]))
    out.append("/// Tables 9-7 and 9-8: total_zeros for 4x4 blocks as (length, code, total_zeros), indexed by tzVlcIndex - 1.")
    out.append("pub const TOTAL_ZEROS_4X4: [&[(u8, u32, u8)]; 15] = [")
    for k in range(1, 16):
        out.append("    &[" + ", ".join(f"({len(b)}, 0b{b}, {p[0]})" for b, p in tz[k]) + "],")
    out.append("];")
    out.append("")

    # ---- Table 9-9 (a) chroma DC 2x2 ---------------------------------------
    p = spec.find_pages("Table 9-9 – total_zeros tables for chroma DC")
    cdc = None
    for pg in p:
        for t in spec.tables(pg):
            if t and t[0] and t[0][0] == "total_zeros" and len(t[1]) == 4:
                cdc = t
    assert cdc is not None
    tzc = {1: [], 2: [], 3: []}
    for r in cdc[2:]:
        z = num(r[0])
        for k in (1, 2, 3):
            b = bits(r[k])
            if b is not None:
                tzc[k].append((b, (z,)))
    assert [len(tzc[k]) for k in (1, 2, 3)] == [4, 3, 2]
    out.append("/// Table 9-9 (a): total_zeros for 2x2 chroma DC as (length, code, total_zeros), indexed by tzVlcIndex - 1.")
    out.append("pub const TOTAL_ZEROS_CHROMA_DC_2X2: [&[(u8, u32, u8)]; 3] = [")
    for k in (1, 2, 3):
        out.append("    &[" + ", ".join(f"({len(b)}, 0b{b}, {p[0]})" for b, p in tzc[k]) + "],")
    out.append("];")
    out.append("")

    # ---- Table 9-10 run_before ---------------------------------------------
    rb = None
    for pg in spec.find_pages("Table 9-10 – Tables for run_before"):
        for t in spec.tables(pg):
            if t and t[0] and t[0][0] == "run_before":
                rb = t
    assert rb is not None
    runs = [[] for _ in range(7)]
    for r in rb[2:]:
        v = num(r[0])
        for k in range(7):
            b = bits(r[1 + k])
            if b is not None:
                runs[k].append((b, (v,)))
    assert [len(x) for x in runs] == [2, 3, 4, 5, 6, 7, 15], [len(x) for x in runs]
    out.append("/// Table 9-10: run_before as (length, code, run_before), indexed by min(zerosLeft, 7) - 1.")
    out.append("pub const RUN_BEFORE: [&[(u8, u32, u8)]; 7] = [")
    for k in range(7):
        out.append("    &[" + ", ".join(f"({len(b)}, 0b{b}, {p[0]})" for b, p in runs[k]) + "],")
    out.append("];")
    out.append("")

    # ---- Table 9-4 coded_block_pattern --------------------------------------
    # Two tables over three pages, each starting at codeNum 0: (a) 0..47 for
    # ChromaArrayType 1 or 2, then (b) 0..15 for ChromaArrayType 0 or 3.
    cbp_tables = []
    cbp_first = spec.find_pages("Table 9-4 – Assignment of codeNum to values of coded_block_pattern")[0]
    for pg in range(cbp_first, cbp_first + 3):
        for t in spec.tables(pg):
            if t and t[0] and t[0][0] == "codeNum":
                for r in t[2:]:
                    k = num(r[0])
                    if k == 0:
                        cbp_tables.append({})
                    cbp_tables[-1][k] = (num(r[1]), num(r[2]))
    assert [sorted(c) for c in cbp_tables] == [list(range(48)), list(range(16))], [sorted(c) for c in cbp_tables]
    cbp_rows, cbp_mono = cbp_tables
    out.append("/// Table 9-4 (ChromaArrayType 1 or 2): coded_block_pattern by codeNum, Intra_4x4/Intra_8x8.")
    out.append("pub const CBP_INTRA: [u8; 48] = [" + ", ".join(str(cbp_rows[k][0]) for k in range(48)) + "];")
    out.append("/// Table 9-4 (ChromaArrayType 1 or 2): coded_block_pattern by codeNum, Inter.")
    out.append("pub const CBP_INTER: [u8; 48] = [" + ", ".join(str(cbp_rows[k][1]) for k in range(48)) + "];")
    out.append("/// Table 9-4 (ChromaArrayType 0 or 3): coded_block_pattern by codeNum, Intra_4x4/Intra_8x8.")
    out.append("pub const CBP_INTRA_MONO: [u8; 16] = [" + ", ".join(str(cbp_mono[k][0]) for k in range(16)) + "];")
    out.append("/// Table 9-4 (ChromaArrayType 0 or 3): coded_block_pattern by codeNum, Inter.")
    out.append("pub const CBP_INTER_MONO: [u8; 16] = [" + ", ".join(str(cbp_mono[k][1]) for k in range(16)) + "];")
    out.append("")

    # ---- Tables 9-12 .. 9-33 CABAC m, n ------------------------------------
    # mn[ctx] = [I, idc0, idc1, idc2], each (m, n) or None.
    mn = {}

    def put(ctx, slot, m, n):
        cur = mn.setdefault(ctx, [None] * 4)
        assert cur[slot] is None or cur[slot] == (m, n), (ctx, slot)
        cur[slot] = (m, n)

    first = spec.find_pages("Table 9-12 – Values of variables m and n")[0]
    last = spec.find_pages("Table 9-33 – Values of variables m and n")[-1]
    for pg in range(first, last + 1):
        for t in spec.tables(pg):
            if not t or not t[0]:
                continue
            h0 = (t[0][0] or "").replace("\n", " ")
            if h0.startswith("Initialization") or (h0 == "" and "Initialization" in " ".join(c or "" for c in t[0])):
                # Single m row / n row, same for all slice types (Tables 9-12, 9-17).
                ctxs = [num(x) for x in t[1][1:]]
                ms = [num(x) for x in t[2][1:]]
                ns = [num(x) for x in t[3][1:]]
                assert t[2][0] == "m" and t[3][0] == "n"
                for c, m, n in zip(ctxs, ms, ns):
                    for s in range(4):
                        put(c, s, m, n)
            elif h0.startswith("Value of"):
                # cabac_init_idc rows (and optionally an "I slices" row).
                ctxs = [num(x) for x in t[1][2:]]
                r = 2
                while r < len(t):
                    label = (t[r][0] or "").replace("\n", " ")
                    assert t[r][1] == "m" and t[r + 1][1] == "n", t[r]
                    slot = 0 if label.startswith("I") else 1 + num(label)
                    for c, m, n in zip(ctxs, t[r][2:], t[r + 1][2:]):
                        if m == "na":
                            continue
                        put(c, slot, num(m), num(n))
                    r += 2
            elif h0 == "ctxIdx":
                # Two side-by-side halves: ctxIdx, (m n) for I, idc0, idc1, idc2.
                hdr = (t[0][1] or "")
                assert hdr.replace("\n", " ") in ("I and SI slices", "I slices"), hdr
                for half in (0, 9):
                    prev = None
                    for r in t[3:]:
                        cell = r[half]
                        if cell in (None, ""):
                            continue
                        c = num(cell)
                        if c in CTXIDX_ERRATA and prev is not None and CTXIDX_ERRATA[c] == prev + 1:
                            c = CTXIDX_ERRATA[c]
                        if prev is not None:
                            assert c == prev + 1, (pg, prev, c)
                        prev = c
                        vals = [num(x) for x in r[half + 1: half + 9]]
                        for s in range(4):
                            put(c, s, vals[2 * s], vals[2 * s + 1])
    # 276 is end_of_slice_flag (no initialization).
    missing = [c for c in range(1024) if c != 276 and c not in mn]
    assert not missing, missing[:20]
    for c in range(11, 60):
        assert mn[c][0] is None and all(mn[c][1:]), c
    for c in list(range(0, 11)) + list(range(60, 460)):
        if c == 276 or c in range(11, 60) or c in (399, 400, 401):
            continue
        assert all(mn[c]), c
    out.append("/// Tables 9-12 to 9-33: CABAC (m, n) by ctxIdx; index 0 is I slices, 1 + cabac_init_idc otherwise.")
    out.append("/// Entries with no value in the specification (ctxIdx 276, and 11..59 for I slices) are (0, 0).")
    out.append("pub const CABAC_INIT_MN: [[(i8, i8); 1024]; 4] = [")
    for s in range(4):
        vals = []
        for c in range(1024):
            v = mn.get(c, [None] * 4)[s] or (0, 0)
            assert -128 <= v[0] <= 127 and -128 <= v[1] <= 127
            vals.append(f"({v[0]}, {v[1]})")
        out.append("    [" + ", ".join(vals) + "],")
    out.append("];")
    out.append("")

    # ---- Table 9-40 ctxBlockCatOffset --------------------------------------
    for pg in spec.find_pages("Table 9-40 – Assignment of ctxIdxBlockCatOffset"):
        for t in spec.tables(pg):
            if t and t[0] and t[0][0] == "Syntax element":
                cats = [num(x) for x in t[1][1:]]
                assert cats == list(range(14))
                for r in t[2:]:
                    name = r[0].upper()
                    out.append(f"/// Table 9-40: ctxBlockCatOffset of {r[0]} by ctxBlockCat.")
                    out.append(f"pub const BLOCK_CAT_OFFSET_{name}: [u16; 14] = [" + ", ".join(str(num(x)) for x in r[1:]) + "];")
    out.append("")

    # ---- Table 9-43 8x8 significance / last ctxIdxInc -----------------------
    sig_frame, sig_field, last = {}, {}, {}
    for pg in spec.find_pages("Table 9-43 – Mapping of scanning position to ctxIdxInc"):
        for t in spec.tables(pg):
            for r in t:
                if r and r[0] and re.fullmatch(r"\d+", r[0] or ""):
                    for base in (0, 4):
                        if r[base] in (None, ""):
                            continue
                        i = num(r[base])
                        sig_frame[i] = num(r[base + 1])
                        sig_field[i] = num(r[base + 2])
                        last[i] = num(r[base + 3])
    assert sorted(sig_frame) == list(range(63)), sorted(sig_frame)
    out.append("/// Table 9-43: ctxIdxInc of significant_coeff_flag (frame coded) for 8x8 blocks by levelListIdx.")
    out.append("/// The table's 63 values, with a 64th 0 so that a scanning position is always in range.")
    out.append("pub const SIG_CTX_INC_8X8_FRAME: [u8; 64] = [" + ", ".join(str(sig_frame[i]) for i in range(63)) + ", 0];")
    out.append("/// Table 9-43: ctxIdxInc of last_significant_coeff_flag for 8x8 blocks by levelListIdx.")
    out.append("/// The table's 63 values, with a 64th 0 so that a scanning position is always in range.")
    out.append("pub const LAST_CTX_INC_8X8: [u8; 64] = [" + ", ".join(str(last[i]) for i in range(63)) + ", 0];")
    out.append("")

    # ---- Table 9-44 rangeTabLPS, 9-45 transIdx -----------------------------
    lps = {}
    for pg in spec.find_pages("Table 9-44 – Specification of rangeTabLPS"):
        for t in spec.tables(pg):
            if t and t[0] and t[0][0] == "pStateIdx" and len(t[0]) == 10:
                for r in t[2:]:
                    for base in (0, 5):
                        lps[num(r[base])] = [num(x) for x in r[base + 1: base + 5]]
    assert sorted(lps) == list(range(64))
    tl, tm = {}, {}
    for pg in spec.find_pages("Table 9-45 – State transition table"):
        for t in spec.tables(pg):
            for i in range(0, len(t) - 2, 3):
                if t[i][0] == "pStateIdx":
                    for k, (x0, b2, c) in enumerate(zip(t[i][1:], t[i + 1][1:], t[i + 2][1:])):
                        tl[num(x0)] = num(b2)
                        tm[num(x0)] = num(c)
    assert sorted(tl) == list(range(64))
    # The same two tables in the layout the arithmetic decoding engine
    # reads them in, so that the engine indexes them with its context byte
    # and nothing is computed at run time.
    lps_by_state = []
    for s_byte in range(128):
        for q in range(4):
            lps_by_state.append(lps[s_byte >> 1][q])
    out.append("/// Table 9-44 by `(pStateIdx << 1 | valMPS) << 2 | qCodIRangeIdx`: the layout")
    out.append("/// the arithmetic decoding engine indexes with its context byte.")
    out.append("pub const RANGE_TAB_LPS_BY_STATE: [u8; 512] = [" + ", ".join(str(v) for v in lps_by_state) + "];")
    next_state = []
    for s_byte in range(128):
        state, mps = s_byte >> 1, s_byte & 1
        next_state.append((tm[state] << 1) | mps)
    for s_byte in range(128):
        state, mps = s_byte >> 1, s_byte & 1
        after = 1 - mps if state == 0 else mps
        next_state.append((tl[state] << 1) | after)
    out.append("/// Table 9-45 as context bytes: entry `i` is the byte after a most probable")
    out.append("/// symbol, entry `128 + i` the byte after a least probable one.")
    out.append("pub const NEXT_STATE: [u8; 256] = [" + ", ".join(str(v) for v in next_state) + "];")
    out.append("")

    # ---- Tables 7-3, 7-4 default scaling lists -----------------------------
    dl = {}
    dl_pages = sorted(set(spec.find_pages("Table 7-3 – Specification of default scaling lists") + spec.find_pages("Table 7-4 – Specification of default scaling lists")))
    if True:
        for pg in dl_pages:
            for t in spec.tables(pg):
                if t and t[0] and t[0][0] == "idx":
                    idxs = [num(x) for x in t[0][1:]]
                    for r in t[1:]:
                        name = r[0].split("[")[0].strip()
                        for i, v in zip(idxs, r[1:]):
                            dl.setdefault(name, {})[i] = num(v)
    for name, n in (("Default_4x4_Intra", 16), ("Default_4x4_Inter", 16), ("Default_8x8_Intra", 64), ("Default_8x8_Inter", 64)):
        assert sorted(dl[name]) == list(range(n)), name
        out.append(f"/// Table 7-3/7-4: {name} in zig-zag scan order.")
        out.append(f"pub const {name.upper()}: [u8; {n}] = [" + ", ".join(str(dl[name][i]) for i in range(n)) + "];")
    out.append("")

    # ---- Tables 8-13, 8-14 scans -------------------------------------------
    def scan(title, n, w):
        res = {}
        for pg in spec.find_pages(title):
            for t in spec.tables(pg):
                if t and t[0] and t[0][0] == "idx":
                    idxs = [num(x) for x in t[0][1:]]
                    for r in t[1:]:
                        if r[0] == "zig-zag":
                            for i, c in zip(idxs, r[1:]):
                                d = c.replace("c", "").replace("\n", "").strip()
                                assert re.fullmatch(r"\d\d", d), c
                                # c_ij: i is the row and j the column, as
                                # Equation 8-299 places r_ij at (xO + j, yO + i).
                                res[i] = int(d[0]) * w + int(d[1])
        assert sorted(res) == list(range(n)), title
        assert sorted(res.values()) == list(range(n)), title
        return [res[i] for i in range(n)]

    z4 = scan("Table 8-13 – Specification of mapping of idx to c for zig-zag and field scan", 16, 4)
    z8 = scan("Table 8-14 – Specification of mapping of idx to c for 8x8 zig-zag", 64, 8)
    out.append("/// Table 8-13: raster position (row * 4 + column) of each zig-zag scan index.")
    out.append("pub const ZIGZAG_4X4: [u8; 16] = [" + ", ".join(map(str, z4)) + "];")
    out.append("/// Table 8-14: raster position (row * 8 + column) of each 8x8 zig-zag scan index.")
    out.append("pub const ZIGZAG_8X8: [u8; 64] = [" + ", ".join(map(str, z8)) + "];")
    out.append("")

    # ---- Table 8-15 QPc ----------------------------------------------------
    qpc = None
    for pg in spec.find_pages("Table 8-15 – Specification of QP as a function of qP"):
        for t in spec.tables(pg):
            if t and t[0] and (t[0][0] or "").startswith("qP"):
                qpc = t
    assert qpc is not None
    q = list(range(30))
    for a2, b2 in zip(qpc[0][2:], qpc[1][2:]):
        assert num(a2) == len(q)
        q.append(num(b2))
    assert len(q) == 52
    out.append("/// Table 8-15: QPc by qPI (identity below 30).")
    out.append("pub const QPC: [u8; 52] = [" + ", ".join(map(str, q)) + "];")
    out.append("")

    # ---- Tables 8-16, 8-17 deblocking --------------------------------------
    alpha, beta, tc0 = {}, {}, {}
    for pg in spec.find_pages("Table 8-16 – Derivation of offset dependent threshold variables"):
        for t in spec.tables(pg):
            if len(t) < 3 or len(t[1]) < 27:
                continue
            idxs = [num(x) for x in t[1][1:]]
            for r in t[2:]:
                lab = (r[0] or "").strip()
                vals = [num(x) for x in r[1:]]
                if lab.startswith("bS"):
                    k = num(lab.split("=")[1])
                    for i, v in zip(idxs, vals):
                        tc0.setdefault(i, {})[k] = v
                elif lab.endswith("′") and len(lab) == 2:
                    #  alpha,  beta (symbol font).
                    tgt = alpha if lab[0] in ("", "α") else beta
                    for i, v in zip(idxs, vals):
                        tgt[i] = v
    assert sorted(alpha) == list(range(52)) and sorted(beta) == list(range(52)) and sorted(tc0) == list(range(52))
    out.append("/// Table 8-16: alpha' by indexA.")
    out.append("pub const ALPHA: [u8; 52] = [" + ", ".join(str(alpha[i]) for i in range(52)) + "];")
